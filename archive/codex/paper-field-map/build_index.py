#!/usr/bin/env python3
"""Rebuild papers/INDEX.md from card files (papers/<track>/*.md).

A card follows papers/CARD_TEMPLATE.md. The index lists, per track, the title line,
whether the full text was read, the matched-comparison verdict and the read priority.
"""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent / "papers"


def section(text, heading):
    m = re.search(rf"^## {re.escape(heading)}\s*\n(.*?)(?=^## |\Z)", text, re.S | re.M)
    return " ".join(m.group(1).split()) if m else ""


def first(text, label):
    m = re.search(rf"^- {re.escape(label)}:\s*(.*)$", text, re.M)
    return m.group(1).strip() if m else ""


lines = ["# Card index", "", "Generated by scripts/build_index.py. Edit cards, not this file.", ""]
for track in sorted(p for p in root.iterdir() if p.is_dir()):
    cards = sorted(track.glob("*.md"))
    lines += [f"## {track.name} ({len(cards)})", "", "| Card | Title | Read | Matched verdict | Priority |", "|---|---|---|---|---|"]
    for c in cards:
        t = c.read_text()
        title = t.splitlines()[0].lstrip("# ").strip() if t else c.stem
        read = first(t, "Source").split("|")[-1].strip()[:40]
        verdict = section(t, "Matched-comparison verdict")[:160]
        prio = section(t, "Read priority")[:100]
        esc = lambda s: s.replace("|", "/")
        lines.append(f"| {c.stem} | {esc(title)[:90]} | {esc(read)} | {esc(verdict)} | {esc(prio)} |")
    lines.append("")
(root / "INDEX.md").write_text("\n".join(lines))
print(f"wrote {root / 'INDEX.md'}")
